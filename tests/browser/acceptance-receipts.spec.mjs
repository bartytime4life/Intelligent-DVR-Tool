import {test,expect} from '@playwright/test';

const receipt = extra => ({schema:'intelligent-dvr.field-byte-check.v1',utc:'2026-11-09T00:00:00+00:00',check:'PASS',
  input_kind:'generated',operator_supplied_revision:'a'.repeat(40),verifier_sha256:'b'.repeat(64),
  field_acceptance:'NOT_ESTABLISHED',source_sha256:'c'.repeat(64),backup_sha256:'c'.repeat(64),
  bytes:100,independent_file:true,review_binding:'NOT_RUN',...extra});
const selected = data => ({name:'generated-byte-receipt.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(data))});
async function open(page) {
  await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
  await page.goto('/#recognition');
  await page.getByRole('group',{name:'Recognition tasks'}).getByRole('button',{name:/Use my existing DVR/}).click();
  await page.locator('.acceptance-receipts > summary').click();
}

test('reads generated byte receipts without sending files or starting work',async({page})=>{
  const writes=[];page.on('request',request=>{if(request.method()==='POST')writes.push(request.url());});
  await open(page);
  await page.getByLabel('Current byte-check receipt',{exact:true}).setInputFiles(selected(receipt()));
  await expect(page.getByText('Receipt reports matching source and backup bytes',{exact:true})).toBeVisible();
  await expect(page.getByText('Generated input only',{exact:false})).toBeVisible();
  await page.getByLabel('Earlier receipt (optional)',{exact:true}).setInputFiles(selected(receipt()));
  await expect(page.getByText('The receipts report the same source bytes.',{exact:true})).toBeVisible();
  await expect(page.getByText('Not established by these receipts',{exact:true})).toBeVisible();
  expect(writes).toEqual([]);
  await page.getByRole('button',{name:'Clear loaded receipts',exact:true}).click();
  await expect(page.getByText('Receipt reports matching source and backup bytes',{exact:true})).toHaveCount(0);
});
test('a bad import keeps the previously interpreted record and clear removes the error',async({page})=>{
  await open(page);
  const current=page.getByLabel('Current byte-check receipt',{exact:true});
  await current.setInputFiles(selected(receipt()));
  await expect(page.getByText('Receipt reports matching source and backup bytes',{exact:true})).toBeVisible();
  await current.setInputFiles(selected({schema:'intelligent-dvr.recognition-review.v1'}));
  await expect(page.getByRole('alert')).toContainText('Last loaded receipt kept');
  await expect(page.getByText('Receipt reports matching source and backup bytes',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Clear loaded receipts',exact:true}).click();
  await expect(page.getByRole('alert')).toHaveCount(0);
});
test('partial coverage and reported CUDA are not promoted to field acceptance',async({page})=>{
  await open(page);
  await page.getByLabel('Current byte-check receipt',{exact:true}).setInputFiles(selected(receipt({review_binding:'MATCHED',
    review_sha256:'d'.repeat(64),reported_backend:'onnxruntime-cuda',reported_coverage:'partial'})));
  await expect(page.getByText('Partial coverage reported',{exact:true})).toBeVisible();
  await expect(page.getByText('CUDA reported · execution needs separate evidence',{exact:true})).toBeVisible();
  await expect(page.getByText('Not established by these receipts',{exact:true})).toBeVisible();
});
